def crc8(data: bytes) -> int:
    c = 0
    for b in data:
        c = CRC8_TABLE[c ^ b]
    return c

from dataclasses import dataclass

@dataclass
class Point:
    angle_deg: float
    distance_mm: int
    intensity: int
    stamp_ns: int

class LiPkgParser:
    """State-machine parser for LDROBOT packets (47 bytes)."""
    def __init__(self, measure_point_hz=21600):
        self.buf = bytearray()
        self.measure_point_hz = measure_point_hz
        self.last_pkg_stamp_ns = None
        self.spin_deg_per_s = 0.0
        self.timestamp_ms = 0

    def feed(self, data: bytes):
        self.buf.extend(data)

    def _find_header(self):
        idx = self.buf.find(bytes([PKG_HEADER]))
        if idx > 0:
            del self.buf[:idx]
        return idx == 0

    def next_packet(self):
        if not self._find_header():
            return None
        if len(self.buf) < PACKET_LEN:
            return None
        if self.buf[1] != PKG_VER_LEN:
            del self.buf[0]
            return None
        pkt = bytes(self.buf[:PACKET_LEN])
        if crc8(pkt[:-1]) != pkt[-1]:
            del self.buf[0]
            return None
        del self.buf[:PACKET_LEN]
        return self._decode(pkt)

    def _u16(self, lo, hi):
        return lo | (hi << 8)

    def _decode(self, pkt: bytes):
        speed = self._u16(pkt[2], pkt[3])             # deg/s
        start_angle_c = self._u16(pkt[4], pkt[5])     # centi-deg
        pts = []
        off = 6
        now_ns = time.time_ns()
        for i in range(POINTS_PER_PACK):
            dist = self._u16(pkt[off], pkt[off+1])
            inten = pkt[off+2]
            off += 3
            pts.append((dist, inten))
        end_angle_c = self._u16(pkt[42], pkt[43])
        ts_ms = self._u16(pkt[44], pkt[45])

        if self.last_pkg_stamp_ns is None:
            self.last_pkg_stamp_ns = now_ns
        current_pack_stamp = now_ns
        step = int((current_pack_stamp - self.last_pkg_stamp_ns) / max(1, (POINTS_PER_PACK - 1)))

        self.spin_deg_per_s = float(speed)
        self.timestamp_ms = ts_ms

        start_deg = start_angle_c / 100.0
        end_deg = end_angle_c / 100.0
        diff = (end_deg - start_deg) % 360.0
        if diff == 0:
            diff = 360.0

        out = []
        for i, (dist, inten) in enumerate(pts):
            frac = i / max(1, (POINTS_PER_PACK - 1))
            ang = (start_deg + frac * diff) % 360.0
            stamp_ns = self.last_pkg_stamp_ns + step * i
            out.append(Point(angle_deg=ang, distance_mm=dist, intensity=inten, stamp_ns=stamp_ns))

        self.last_pkg_stamp_ns = current_pack_stamp
        return out
