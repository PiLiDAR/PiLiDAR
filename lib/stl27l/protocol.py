from dataclasses import dataclass

# Protocol assumptions per LDROBOT LiPkg (SDK v3.0.5):
# - Header: 0x54
# - VerLen: 0x2C ("Version+Length" field), full packet 47 bytes
# - Points per packet: 12
# - Layout: [0]Header [1]VerLen [2..3]Speed [4..5]StartAngle [6..41] 12*(DistLo,DistHi,Int)
#           [42..43]EndAngle [44..45]Timestamp [46]CRC8
# - Angle in centi-degrees (0..35999), Distance in mm, Intensity 0..255

PKG_HEADER = 0x54
PKG_VER_LEN = 0x2C
POINTS_PER_PACK = 12
PACKET_LEN = 47

